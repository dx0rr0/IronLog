import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { createNavigationHistory } from '../src/infrastructure/navigation/navigation-history.js';
const dom = new JSDOM('', { url: 'https://ironlog.test/' });
const { window } = dom;
let screen;
const nav = createNavigationHistory(window, value => { screen = value; });
let stop = nav.start();
stop(); stop = nav.start();
assert.equal(window.history.length, 1, 'StrictMode remount does not duplicate root');
const settle = () => new Promise(resolve => setTimeout(resolve, 30));
nav.navigate(() => ({ tab: 'exercises', view: null }));
nav.navigate(current => ({ ...current, view: { kind: 'exercise', data: { id: 'cust_1', secret: 'never in history' } } }));
assert.equal(window.history.length, 3);
assert.equal(JSON.stringify(window.history.state).includes('secret'), false);
window.history.back(); await settle();
assert.equal(screen.tab, 'exercises'); assert.equal(screen.view, null);
window.history.forward(); await settle();
assert.equal(screen.view.data.id, 'cust_1');
window.history.back(); await settle();
nav.navigate(() => ({ tab: 'home', view: null })); await settle();
assert.equal(screen.tab, 'home');
nav.navigate(() => ({ tab: 'home', view: { kind: 'active' } }));
let closed = 0;
nav.layer(() => { closed++; });
window.history.back(); await settle();
assert.equal(closed, 1); assert.equal(screen.view.kind, 'active');
const closePicker = nav.layer(() => { closed++; });
closePicker(); await settle();
window.history.back(); await settle();
assert.equal(screen.view, null, 'UI close consumed the overlay entry');
assert.equal(closed, 1, 'UI close did not invoke the Android-back callback');

nav.navigate(() => ({ tab: 'routines', view: null }));
nav.navigate(current => ({ ...current, view: { kind: 'newRoutine' } }));
let asked = 0;
const unguard = nav.guard(() => { asked++; return true; });
window.history.back(); await settle(); await settle();
assert.equal(asked, 1); assert.equal(nav.screen.view.kind, 'newRoutine');
nav.layer(() => { closed++; });
window.history.back(); await settle();
assert.equal(closed, 2); assert.equal(asked, 1, 'closing confirmation does not leave the editor');
nav.navigate(() => ({ tab: 'routines', view: null })); await settle();
assert.equal(screen.view, null); assert.equal(asked, 1, 'confirmed UI exit bypasses guard');
unguard();

nav.navigate(current => ({ ...current, view: { kind: 'active' } }));
nav.layer(() => { closed++; });
nav.navigate(current => ({ ...current, view: { kind: 'summary', data: { id: 'saved' } } }), { replace: true });
await settle();
assert.equal(screen.view.kind, 'summary');
window.history.back(); await settle();
assert.equal(screen.view, null, 'finished workout does not remain behind summary');
nav.navigate(() => ({ tab: 'settings', view: null }));
const release = nav.layer(() => { closed++; });
release();
nav.navigate(() => ({ tab: 'exercises', view: null }));
await settle();
assert.equal(screen.tab, 'exercises', 'rapid close plus navigation is queued');
stop(); dom.window.close();
console.log('Native history, overlays, guards, rapid navigation, summary and StrictMode passed');

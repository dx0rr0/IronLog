import assert from 'node:assert/strict';
import { joinSuperset, splitSuperset, moveTrainingEntry, normalizeSupersets,
  supersetInfo, updateTrainingEntry, restAfterSet, nextSupersetSet, trainingBlocks, moveTrainingBlock } from '../src/domain/training/supersets.js';
import { repeatSession } from '../src/domain/training/workout-intelligence.js';
import { routineDraftFromSession } from '../src/domain/training/routine-from-session.js';
import { sessionVolume } from '../src/domain/training/session-utils.js';
import { storage } from '../src/infrastructure/storage/storage.js';
import 'fake-indexeddb/auto';

const entry = (exerciseId, count = 2, restSeconds = 60) => ({ exerciseId, restSeconds,
  sets: Array.from({ length: count }, () => ({ weight: 20, reps: 10, done: false })) });
const original = [entry('a'), entry('b', 1, 90), entry('c'), entry('d')];
let grouped = joinSuperset(original, 0, 'ss-1');
assert.equal(original[0].supersetId, undefined, 'grouping does not mutate originals');
assert.equal(grouped[1].restSeconds, 90);
assert.equal(supersetInfo(grouped, 1).position, 2);
assert.deepEqual(nextSupersetSet(grouped, 0), { entryIndex: 0, setIndex: 0 });
grouped[0].sets[0] = { ...grouped[0].sets[0], done: true };
assert.equal(restAfterSet(grouped, 0, 0), 0, 'no rest between exercises');
assert.deepEqual(nextSupersetSet(grouped, 0), { entryIndex: 1, setIndex: 0 });
grouped[1].sets[0] = { ...grouped[1].sets[0], done: true };
assert.equal(restAfterSet(grouped, 1, 0), 90, 'rest once the round is complete');
grouped[0].sets[1] = { ...grouped[0].sets[1], done: true };
assert.equal(restAfterSet(grouped, 0, 1), 90, 'unequal set counts remain usable');
assert.equal(nextSupersetSet(grouped, 0), null);
const reversed = joinSuperset([entry('a'), entry('b')], 0, 'reverse');
reversed[1].sets[0].done = true;
assert.equal(restAfterSet(reversed, 1, 0), 0, 'checking the last member early cannot rest');
reversed[0].sets[0].done = true;
assert.equal(restAfterSet(reversed, 0, 0), 60);
assert.equal(restAfterSet([entry('solo')], 0, 0), 0);
assert.equal(restAfterSet([{ ...entry('solo'), sets: [{ done: true }] }], 0, 0), 60);
assert.deepEqual(moveTrainingEntry(grouped, 1, 1).map(e => e.exerciseId), ['c', 'a', 'b', 'd']);
assert.deepEqual(moveTrainingEntry(moveTrainingEntry(grouped, 0, 1), 1, -1), grouped);
const twoGroups = joinSuperset(grouped, 2, 'ss-2');
assert.deepEqual(moveTrainingEntry(twoGroups, 1, 1).map(e => e.exerciseId), ['c', 'd', 'a', 'b']);
assert.deepEqual(trainingBlocks(twoGroups), [{ start: 0, end: 1 }, { start: 2, end: 3 }]);
assert.deepEqual(trainingBlocks(grouped), [{ start: 0, end: 1 }, { start: 2, end: 2 }, { start: 3, end: 3 }]);
assert.deepEqual(moveTrainingBlock(grouped, 0, 2).map(e => e.exerciseId), ['c', 'd', 'a', 'b'], 'superset drags as one block');
assert.deepEqual(moveTrainingBlock(grouped, 2, 0).map(e => e.exerciseId), ['d', 'a', 'b', 'c']);
assert.deepEqual(moveTrainingBlock(grouped, 1, 1), grouped);
assert.deepEqual(trainingBlocks(twoGroups), [{ start: 0, end: 1 }, { start: 2, end: 3 }]);
assert.deepEqual(trainingBlocks(grouped), [{ start: 0, end: 1 }, { start: 2, end: 2 }, { start: 3, end: 3 }]);
assert.deepEqual(moveTrainingBlock(grouped, 0, 2).map(e => e.exerciseId), ['c', 'd', 'a', 'b'], 'superset drags as one block');
assert.deepEqual(moveTrainingBlock(grouped, 2, 0).map(e => e.exerciseId), ['d', 'a', 'b', 'c']);
assert.deepEqual(moveTrainingBlock(grouped, 1, 1), grouped);
assert.equal(new Set(joinSuperset(twoGroups, 1, 'merged').map(e => e.supersetId)).size, 1);
assert.equal(joinSuperset(grouped, 1, 'extended')[2].supersetId, 'ss-1');
assert.ok(splitSuperset(grouped, 1).every(e => !e.supersetId));
assert.equal(normalizeSupersets(grouped.filter((_, i) => i !== 0))[0].supersetId, undefined);
assert.ok(normalizeSupersets([grouped[0], entry('other'), grouped[1]]).every(e => !e.supersetId));
assert.deepEqual(normalizeSupersets(original.map(({ supersetId, ...e }) => e)), original);
assert.deepEqual(updateTrainingEntry(grouped, 1, { restSeconds: 120 }).slice(0, 2).map(e => e.restSeconds), [120, 120]);

const exMap = Object.fromEntries(['a', 'b', 'c', 'd'].map(id => [id, { id, type: 'weight_reps' }]));
const source = { id: 'source', entries: grouped };
const repeated = repeatSession(source, exMap, 123456);
assert.equal(repeated.entries[1].supersetId, 'ss-1');
assert.ok(repeated.entries.every(e => e.sets.every(s => !s.done)));
assert.equal(sessionVolume(source), 600, 'group metadata does not double count volume');
const draft = routineDraftFromSession(source, exMap);
assert.equal(draft.exercises[1].supersetId, 'ss-1');
const filtered = routineDraftFromSession(source, { ...exMap, b: { ...exMap.b, hidden: true } });
assert.equal(filtered.exercises[0].supersetId, undefined, 'filtered drafts clear orphan groups');
const missing = repeatSession(source, { a: exMap.a }, 123456);
assert.equal(missing.entries[0].supersetId, undefined);
await storage.set('superset-test', { source, draft, repeated });
assert.deepEqual(await storage.get('superset-test'), { source, draft, repeated });
assert.equal(JSON.parse(JSON.stringify(source)).entries[1].supersetId, 'ss-1');
console.log('Superset rounds, ordering, compatibility, templates and persistence checks passed');
